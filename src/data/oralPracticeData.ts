/**
 * Extrae vocabulario y expresiones orales directamente desde cualquier texto.
 * Si el profesor pega un texto personalizado o se cambia la lectura, genera
 * hasta 30 palabras significativas, separadas en sílabas y con su frase en contexto.
 */
export function extractWordsFromText(
  text: string,
  nivel: string,
  unidad: string
): OralPracticeItem[] {
  if (!text || text.trim().length === 0) {
    return [];
  }

  // Dividir en oraciones para encontrar el contexto
  const sentences = text
    .replace(/\n+/g, ' ')
    .split(/(?<=[.?!])\s+/)
    .map((s) => s.trim())
    .filter((s) => s.length > 5);

  // Extraer palabras únicas válidas (longitud >= 4, no números puros, sin stopwords)
  const rawWords = text.match(/[a-zA-ZáéíóúüñÁÉÍÓÚÜÑ]+/g) || [];
  const wordFrequency = new Map<string, number>();

  rawWords.forEach((raw) => {
    const lower = raw.toLowerCase();
    if (lower.length >= 4 && !STOPWORDS.has(lower)) {
      wordFrequency.set(lower, (wordFrequency.get(lower) || 0) + 1);
    }
  });

  // Ordenar por longitud y frecuencia para obtener palabras representativas y ricas
  const candidateWords = Array.from(wordFrequency.keys())
    .sort((a, b) => b.length - a.length || (wordFrequency.get(b) || 0) - (wordFrequency.get(a) || 0))
    .slice(0, 30);

  return candidateWords.map((word, index) => {
    // Capitalizar primera letra
    const capitalized = word.charAt(0).toUpperCase() + word.slice(1);
    const syllables = syllabifyWord(capitalized);
    const silabeoStr = syllables.join(' - ');

    // Buscar una oración del texto donde aparezca
    const contextSentence =
      sentences.find((s) => s.toLowerCase().includes(word.toLowerCase())) ||
      `En el texto aparece la palabra «${capitalized}».`;

    return {
      id: `custom-${index + 1}`,
      nivel,
      unidad,
      palabra: capitalized,
      silabeo: silabeoStr,
      pistaFonema: `Pronuncia con claridad cada sílaba: ${silabeoStr}`,
      fraseContexto: contextSentence.length > 120 ? `${contextSentence.slice(0, 117)}...` : contextSentence,
      tipo: 'palabra',
    };
  });
}

/**
 * Obtiene la lista de palabras para práctica oral (aprox. 30 palabras).
 * Si hay palabras preestablecidas para la unidad, las usa.
 * Si el texto actual difiere o se solicita dinámicamente, extrae palabras del texto.
 */
export function getOralPracticeForNivelAndUnit(
  nivel: string,
  unitNumero: string,
  activeText?: string
): OralPracticeItem[] {
  // Buscar palabras preestablecidas de la unidad
  const presets = PRESET_ORAL_ITEMS.filter((item) => {
    if (item.nivel !== nivel) return false;
    return (
      item.unidad === unitNumero ||
      unitNumero.includes(item.unidad) ||
      item.unidad.includes(unitNumero)
    );
  });

  // Si tenemos presets suficientes (>= 20), retornarlos
  if (presets.length >= 20 && !activeText) {
    return presets;
  }

  // Si se entregó un texto activo y no hay suficientes presets para ese texto, extraerlas
  if (activeText && activeText.length > 40) {
    const extracted = extractWordsFromText(activeText, nivel, unitNumero);
    if (extracted.length > 0) {
      // Si tenemos presets que coinciden con el texto, darles prioridad y rellenar con extraídas
      const textLower = activeText.toLowerCase();
      const matchingPresets = presets.filter((p) => textLower.includes(p.palabra.toLowerCase()));
      const seen = new Set(matchingPresets.map((p) => p.palabra.toLowerCase()));

      const combined: OralPracticeItem[] = [...matchingPresets];
      for (const item of extracted) {
        if (!seen.has(item.palabra.toLowerCase()) && combined.length < 30) {
          seen.add(item.palabra.toLowerCase());
          combined.push(item);
        }
      }
      if (combined.length >= 10) {
        return combined;
      }
      return extracted;
    }
  }

  // Si no hay texto activo pero los presets existen
  if (presets.length > 0) {
    return presets;
  }

  // Si aún no hay presets para esa unidad específica, extraer del texto activo
  if (activeText) {
    return extractWordsFromText(activeText, nivel, unitNumero);
  }

  return [];
}
