export function getHistoriaSampleTextsForNivel(nivel: string): SampleMineducText[] {
  return MINEDUC_HISTORIA_TEXTS.filter((sample) => sample.nivel === nivel);
}

export function getHistoriaSampleTextForNivelAndUnit(
  nivel: string,
  unitNumero: string
): SampleMineducText | undefined {
  return MINEDUC_HISTORIA_TEXTS.find((sample) => {
    if (sample.nivel !== nivel) return false;
    return (
      sample.unidad === unitNumero ||
      unitNumero.includes(sample.unidad) ||
      sample.unidad.includes(unitNumero)
    );
  });
}
